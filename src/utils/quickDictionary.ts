/**
 * Quick lookup helper for immediate instant translation without waiting for network/AI.
 */
export function getQuickTranslation(word: string, targetLang: string, baseLang: string): string | null {
  if (!word) return null;
  const langKey = targetLang.toLowerCase().trim();
  const clean = word.toLowerCase().trim();

  // If baseLang is English (or similar), lookup directly from common table
  if (baseLang.toLowerCase().includes('english') || baseLang === 'English') {
    const table = COMMON_VOCAB_TRANSLATIONS[langKey];
    if (table && table[clean]) {
      return table[clean];
    }
  }

  return null;
}
